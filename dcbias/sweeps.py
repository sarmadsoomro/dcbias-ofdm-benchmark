"""Run the one-factor-at-a-time sweeps of config.json "sweeps".

One run per swept value (value and stress lists) plus each _joint control, every run with the
_design overrides (50 units). Each run is generate.generate followed by evaluate.task_main
into runs/<prefix>-<key>=<value>/. A run whose results_main.json exists is skipped, so an
interrupted sweep resumes (same code SHA only); a directory without results (a killed run) must be removed by hand.

Usage: python -m dcbias.sweeps --prefix sweep --workers 8 [--dry-run]
       python -m dcbias.sweeps --twins --workers 8 [--dry-run]   (device-shift twins, evaluate.SHIFT)
"""
import argparse
import json
import subprocess
import sys

from dcbias import evaluate as E
from dcbias import generate as G
from dcbias import physics as V


def runs(cfg):
    """(name, overrides) for every sweep run, design overrides included."""
    sw = cfg["sweeps"]
    out = []
    for key, spec in sw.items():
        if key.startswith("_"):
            continue
        for v in spec.get("value", []) + spec.get("stress", []):
            out.append((f"{key}={json.dumps(v)}", {key: v}))
    for joint in sw["_joint"]:
        out.append(("joint:" + ",".join(f"{k}={json.dumps(v)}" for k, v in joint.items()), dict(joint)))
    out.append(("nominal", {}))  # the reference run at the same 50-unit design
    return [(name, sw["_design"] | o) for name, o in out]


DATA_CODE = ["dcbias/physics.py", "dcbias/generate.py", "dcbias/config.json"]


def same_data_code(sha):
    """True when the files that determine generated data are unchanged between sha and HEAD."""
    return subprocess.run(["git", "diff", "--quiet", sha, "HEAD", "--", *DATA_CODE], cwd=G.REPO_DIR).returncode == 0


def rows_reproduce(out, cfg, n=20):
    """True when the first n rows of an existing twin regenerate exactly at HEAD (states and curves).
    Lets a data-code change that leaves existing LED forms untouched (091cf01: new tsonev_cubic_spread
    form) keep earlier twins, by evidence rather than by trusting the diff."""
    import numpy as np
    import pandas as pd
    df = pd.read_csv(out / "states.csv", low_memory=False)
    cv = np.load(out / "curves.npz")
    design = {r["state_id"]: r for r in G.design(cfg) if r["split"] == "test_id"}
    for i, sid in enumerate(df["state_id"].to_numpy()[:n]):
        row, curves = G.simulate((cfg, design[sid]))
        for k, v in row.items():
            a = df[k].to_numpy()[i]
            if not (a == v or (isinstance(v, float) and np.isclose(a, v, rtol=1e-12, atol=0))):
                return False
        for k, v in curves.items():
            if not np.array_equal(cv[k][i][: len(v)], v):
                return False
    return True


def twins(workers, dry_run, nominal="baseline"):
    """Shifted twins for the device-shift arm (E.SHIFT): the default design's test_id units only, one
    run per shift, into runs/<E.TWIN_PREFIX><name>/. An existing directory is skipped if its
    generating code is clean and equal to HEAD's data code; generate() never
    overwrites. The config must equal the nominal run's before any generation."""
    if V.load_config() != json.loads((G.RUNS_DIR / nominal / "provenance.json").read_text())["config"]:
        raise RuntimeError(f"config.json differs from {nominal}'s config: twins would not be twins")
    if G.git_info()["dirty"]:
        raise RuntimeError("dcbias/ has uncommitted changes: commit before generating twins")
    for name, ov in E.SHIFT.items():
        out = G.RUNS_DIR / f"{E.TWIN_PREFIX}{name}"
        if out.exists():
            git = json.loads((out / "provenance.json").read_text())["git"]
            if git["dirty"]:
                raise RuntimeError(f"{out.name} was generated by dirty code")
            if not same_data_code(git["sha"]):
                if not rows_reproduce(out, V.load_config(overrides=ov)):
                    raise RuntimeError(f"{out.name} was generated by other data code ({git['sha'][:7]}) and does not regenerate at HEAD")
                print(f"keep {out.name}: data code {git['sha'][:7]} != HEAD, first 20 rows regenerate exactly", flush=True)
            print(f"skip {out.name}: done")
            continue
        print(f"twin {out.name}: {ov}", flush=True)
        if not dry_run:
            G.generate(V.load_config(overrides=ov), out, workers, splits=["test_id"])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--prefix")
    ap.add_argument("--twins", action="store_true", help="generate the device-shift twins instead of the sweeps")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    if a.twins:
        return twins(a.workers, a.dry_run)
    if not a.prefix:
        ap.error("--prefix is required for the sweeps")
    base = V.load_config()
    for name, ov in runs(base):
        safe = name.replace(":", "_").replace(",", "_").replace('"', "")
        out = G.RUNS_DIR / f"{a.prefix}-{safe}"
        if (out / "results_main.json").exists():
            # resume only a run made by this code; never mix code versions silently
            sha = json.loads((out / "provenance.json").read_text())["git"]["sha"]
            if sha != G.git_info()["sha"]:
                raise RuntimeError(f"{out.name} was generated by {sha[:7]}, not HEAD: use a new --prefix")
            print(f"skip {out.name}: done")
            continue
        print(f"run  {out.name}: {ov}", flush=True)
        if a.dry_run:
            continue
        G.generate(V.load_config(overrides=ov), out, a.workers)
        E.task_main(out, a.workers)


if __name__ == "__main__":
    sys.exit(main())
