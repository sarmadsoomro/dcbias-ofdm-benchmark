"""Emit every number in a run's results_*.json as a LaTeX macro (in-text numbers come
from the pipeline, never by hand).

    \\vnum{main/test/test_id/B7_bayes/mean_regret}   -> 0.001589 (4 significant figures, never exponent notation)
    \\vnum[2]{main/confirmatory/delta/test_id/point} -> 0.00011  (2 significant figures)

The key is the JSON path with the results_<task> prefix; list records are keyed by their identifying
fields (sensing/cells/lambda_T=4,lambda_W=16/matched/regret_wave), other list items by index
(main/confirmatory/delta/test_id/ci/0). A key that does not exist stops the LaTeX build. Booleans
emit true/false; strings are escaped. Floats keep significant trailing zeros (0.0020 at 2 figures)
and a negative sign prints as a typographic minus; -0 prints as 0. A null leaf gets no macro, so
citing it stops the build (also NaN and inf). \\vnum is not expandable: use it in text, not inside \\num{} or pgfmath.
The manuscript loads the output with \\input.

Usage: python -m dcbias.macros <run_dir> [-o <file.tex>]   (default <run_dir>/paper_numbers.tex)
"""
import argparse
import json
import math
import sys

from decimal import Decimal
from pathlib import Path

HEADER = r"""% Generated by dcbias/macros.py from RUN -- do not edit by hand.
\makeatletter
\newcommand{\vnum}[2][4]{\@ifundefined{dcb@#2}{\errmessage{number '#2' not in results JSON}}{%
  \ifnum#1=4 \csname dcb@#2\endcsname\else\csname dcb@#2@#1\endcsname\fi}}
"""


# Fields that identify an item of a list of records (sensing cells, learning rows, B8 frontier, ...)
ID_KEYS = ("lambda_T", "lambda_W", "lambda_link", "units", "seed", "method", "iterations")


def item_key(i, v):
    """A list item's path segment: its identifying fields (lT=4,lW=16) when it is a record that has any,
    so a citation keeps its meaning when list order changes; else its index."""
    if isinstance(v, dict) and any(k in v for k in ID_KEYS):
        return ",".join(f"{k}={v[k]}" for k in ID_KEYS if k in v)
    return str(i)


def leaves(obj, path=""):
    """(path, value) for every scalar leaf; list items keyed by item_key, which must be unique."""
    if isinstance(obj, dict):
        items = obj.items()
    elif isinstance(obj, list):
        items = [(item_key(i, v), v) for i, v in enumerate(obj)]
        if len({k for k, _ in items}) != len(items):
            raise ValueError(f"list items under {path!r} are not uniquely identified")
    else:
        yield path, obj
        return
    for k, v in items:
        yield from leaves(v, f"{path}/{k}" if path else str(k))


ESC = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}",
       "^": r"\textasciicircum{}", "~": r"\textasciitilde{}"}


def fmt(v, sig):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v).replace("-", r"\ensuremath{-}")
    if isinstance(v, float):
        t = format(Decimal(f"{v:.{sig - 1}e}"), "f")  # round to sig figures, then positional; keeps 0.0020
        if t.startswith("-"):
            t = t[1:] if not t.strip("-0.") else r"\ensuremath{-}" + t[1:]
        return t
    return "".join(ESC.get(c, c) for c in str(v))


def render(run_dir):
    run_dir = Path(run_dir)
    lines = [HEADER.replace("RUN", run_dir.name)]
    for f in sorted(run_dir.glob("results_*.json")):
        task = f.stem.removeprefix("results_")
        for path, v in leaves(json.loads(f.read_text()), task):
            if v is None or (isinstance(v, float) and not math.isfinite(v)):
                continue  # no macro: citing a null / NaN / inf leaf stops the build
            if any(c in path for c in "{}\\%#~"):
                raise ValueError(f"key not usable in a csname: {path}")
            lines.append(rf"\expandafter\def\csname dcb@{path}\endcsname{{{fmt(v, 4)}}}")
            for sig in (1, 2, 3):  # every leaf, so \vnum[n] on an int or flag still resolves
                lines.append(rf"\expandafter\def\csname dcb@{path}@{sig}\endcsname{{{fmt(v, sig)}}}")
    lines.append(r"\makeatother")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dir")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    out = Path(a.out) if a.out else Path(a.run_dir) / "paper_numbers.tex"
    out.write_text(render(a.run_dir))
    print(f"wrote {out}")


if __name__ == "__main__":
    sys.exit(main())
